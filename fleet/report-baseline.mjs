/**
 * Renders fleet/BASELINE.md from fleet/baseline.json.
 *
 * Generated rather than written, for the same reason mock.defaults.json is: a hand-kept table of
 * numbers drifts from the run that produced it, and drifts silently. Regenerate with
 *   node fleet/audit-static.mjs --json fleet/baseline.json && node fleet/report-baseline.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(fs.readFileSync(path.join(ROOT, 'fleet/baseline.json'), 'utf8'));
const sites = data.sites;
const stamp = process.argv[2] || 'unstamped';

const totals = {};
for (const s of sites) for (const f of s.findings) {
  totals[f.id] = totals[f.id] || { count: 0, sites: 0, severity: f.severity, guide: f.guide };
  totals[f.id].count += f.count;
  totals[f.id].sites += 1;
}
const flagged = sites.filter((s) => s.score > 0).sort((a, b) => b.score - a.score);
const clean = sites.filter((s) => s.score === 0);
const lines = sites.reduce((a, s) => a + (s.lines || 0), 0);

const out = [];
out.push(`# Fleet baseline — source screen`);
out.push('');
out.push(`Generated by \`fleet/report-baseline.mjs\` from \`fleet/audit-static.mjs\`. Run stamp: ${stamp}.`);
out.push('');
out.push(`${sites.length} sites, ${lines.toLocaleString()} lines of source. **${flagged.length} sites carry at least one finding**; ${clean.length} are clean on this screen.`);
out.push('');
out.push('> This is a screen, not a verdict — it reads source and cannot tell whether a handler');
out.push('> does anything real. See `fleet/README.md` for its calibration against the one app with');
out.push('> runtime ground truth, where it was right and the runtime probe was wrong.');
out.push('');
out.push('## By detector');
out.push('');
out.push('| detector | severity | hits | sites | completeness-guide criterion |');
out.push('|---|---|---:|---:|---|');
for (const [id, t] of Object.entries(totals).sort((a, b) => b[1].count - a[1].count)) {
  out.push(`| \`${id}\` | ${t.severity} | ${t.count} | ${t.sites} | ${t.guide} |`);
}
out.push('');
out.push('## Sites with findings');
out.push('');
out.push('Weighted score: high = 3, medium = 1, low = 0.25.');
out.push('');
out.push('| site | score | findings |');
out.push('|---|---:|---|');
for (const s of flagged) {
  const f = s.findings.sort((a, b) => b.count - a.count).map((x) => `\`${x.id}\`×${x.count}`).join(', ');
  out.push(`| ${s.site} | ${Math.round(s.score)} | ${f} |`);
}
out.push('');
out.push('## Clean on this screen');
out.push('');
out.push('Clean here means no source-level fake affordance was detected. It does **not** mean the');
out.push('app was verified: none of these has a runtime harness, so nothing has clicked them.');
out.push('');
out.push(clean.map((s) => s.site).join(', ') + '.');
out.push('');

fs.writeFileSync(path.join(ROOT, 'fleet/BASELINE.md'), out.join('\n'));
console.log(`fleet/BASELINE.md written — ${flagged.length} flagged, ${clean.length} clean`);
